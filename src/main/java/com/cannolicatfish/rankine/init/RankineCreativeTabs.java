    public static final DeferredRegister<CreativeModeTab> CREATIVE_MODE_TABS = DeferredRegister.create(Registries.CREATIVE_MODE_TAB, ProjectRankine.MODID);

    /**
     * Pendants that spawned pre-cursed in 1.18.2. Kept as an explicit list because the totem
     * classes share no common supertype, and Totem of Cobbling deliberately was not one of them.
     */
    private static final List<Class<?>> CURSED_PENDANTS = List.of(
            BlazingTotemItem.class, EnduringTotemItem.class, HasteTotemItem.class,
            InfusingTotemItem.class, InvigoratingTotemItem.class, LevitationTotemItem.class,
            LuckTotemItem.class, PoweringTotemItem.class, RepulsionTotemItem.class,
            SofteningTotemItem.class, SpeedTotemItem.class);

    /**
     * Replaces the 1.18.2 {@code Item#fillItemCategory} overrides, which 1.21 removed.
     * Alloy items with no default recipe expand into one stack per known alloy; glass cutters
     * and pendants come pre-enchanted exactly as they used to.
     */
    private static void emit(CreativeModeTab.ItemDisplayParameters params, CreativeModeTab.Output output, Item item) {
        if (item instanceof IAlloyItem alloy && alloy.getDefaultRecipe() == null) {
            List<ItemStack> alloyed = AlloyCustomHelper.getItemsFromAlloying(item);
            List<ItemStack> crafted = AlloyCustomHelper.getItemsFromAlloyCrafting(item);
            if (alloyed.isEmpty() && crafted.isEmpty()) {
                output.accept(item); // recipes not loaded yet — fall back to the plain item
                return;
            }
            alloyed.forEach(output::accept);
            crafted.forEach(output::accept);
            return;
        }

        if (item instanceof GlassCutterItem) {
            output.accept(enchanted(params, item, Enchantments.SILK_TOUCH));
            return;
        }

        if (CURSED_PENDANTS.contains(item.getClass()) && Config.GENERAL.PENDANT_CURSE.get()) {
            output.accept(enchanted(params, item, Enchantments.VANISHING_CURSE));
            return;
        }

        output.accept(item);
    }

    /**
     * Emits every item-bearing block of a block group (stones, bricks, cements, dripstones,
     * sandstones, woods). In 1.18.2 these ~1,900 BlockItems got their creative tab from each
     * group's shared Item.Properties (.tab(...)); the port removed those calls, and because the
     * group classes discard their DeferredItem handles, the items appeared in NO tab (and thus
     * not in creative search either) — refractory bricks were the reported casualty.
     *
     * <p>The air-filter and dedupe are load-bearing, not defensive: wood groups contain wall-sign
     * blocks (no own item — asItem() is the standing sign's item, a duplicate) and potted saplings
     * (asItem() == AIR), and CreativeModeTab's Output.accept THROWS on both empty stacks and
     * duplicate entries, which would crash every tab build.
     */
    private static void emitBlocks(CreativeModeTab.ItemDisplayParameters params, CreativeModeTab.Output output, List<Block> blocks) {
        java.util.Set<Item> seen = new java.util.HashSet<>();
        for (Block b : blocks) {
            if (b == null) continue; // wood getters return null entries for absent variants (bamboo has no logs/leaves)
            Item i = b.asItem();
            if (i == Items.AIR || !seen.add(i)) continue;
            emit(params, output, i);
        }
    }

    /** Enchantments are datapack entries in 1.21, so the holder comes from the tab's lookup provider. */
    private static ItemStack enchanted(CreativeModeTab.ItemDisplayParameters params, Item item, ResourceKey<Enchantment> key) {
        ItemStack stack = new ItemStack(item);
        params.holders().lookup(Registries.ENCHANTMENT)
                .flatMap(reg -> reg.get(key))
                .ifPresent((Holder.Reference<Enchantment> holder) -> stack.enchant(holder, 1));
        return stack;
    }

